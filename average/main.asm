%macro print 2              ; макрос для вывода текста на экран
    mov rax, 1              ; номер команды записи (sys_write)
    mov rdi, 1              ; выводим в стандартный вывод (экран)
    mov rsi, %2             ; кладем адрес строки, которую выводим
    mov rdx, %1             ; кладем сколько байт нужно вывести
    syscall                 ; вызываем операционную систему
%endmacro                   ; конец макроса

section .data               ; секция с начальными данными
    colon       db ": "     ; строка с двоеточием и пробелом
    len_colon   equ $ - colon ; длина строки с двоеточием (2 байта)
    newline     db 10       ; символ переноса на новую строку (\n)
    minus       db '-'      ; символ минуса для отрицательного ответа
    msg_err     db ": файл испорчен", 10 ; текст ошибки с переносом строки
    len_err     equ $ - msg_err ; длина текста ошибки

section .bss                ; секция для переменных без начального значения
    filename    resq 1      ; переменная под адрес имени файла (8 байт)
    fd          resq 1      ; переменная под номер открытого файла (дескриптор)
    bytes_read  resq 1      ; сколько всего байт прочитали из файла
    buffer      resb 4096   ; буфер памяти на 4096 байт для текста файла
    digit       resb 1      ; один байт для печати отдельной цифры

    sum1        resq 1      ; сумма чисел из первой строки
    count1      resq 1      ; количество чисел в первой строке
    sum2        resq 1      ; сумма чисел из второй строки
    count2      resq 1      ; количество чисел во второй строке

section .text               ; секция с командами программы
    global _start           ; делаем точку входа видимой снаружи

_start:                     ; начало выполнения программы
    cmp qword [rsp], 2      ; проверяем, передали ли имя файла при запуске
    jl exit_silent          ; если имя файла не передали, просто выходим

    mov rax, [rsp + 16]     ; берем адрес строки с именем файла из аргументов
    mov [filename], rax     ; сохраняем адрес имени файла в переменную

    mov rax, 2              ; номер команды открытия файла (sys_open)
    mov rdi, [filename]     ; передаем путь к файлу
    xor rsi, rsi            ; открываем только для чтения (режим 0)
    xor rdx, rdx            ; стандартные права (0)
    syscall                 ; просим систему открыть файл
    cmp rax, 0              ; проверяем, успешно ли открылся файл
    jl show_err             ; если вернулось число меньше 0, идем на ошибку
    mov [fd], rax           ; сохраняем номер файла в переменную

    mov rax, 0              ; номер команды чтения (sys_read)
    mov rdi, [fd]           ; из какого файла читать
    mov rsi, buffer         ; куда сохранять прочитанные данные
    mov rdx, 4096           ; читаем максимум 4096 байт
    syscall                 ; читаем файл
    cmp rax, 0              ; проверяем, сколько байт прочиталось
    jle show_err            ; если 0 или меньше, файл пустой или ошибка
    mov [bytes_read], rax   ; сохраняем число прочитанных байт

    mov rax, 3              ; номер команды закрытия файла (sys_close)
    mov rdi, [fd]           ; какой файл закрыть
    syscall                 ; закрываем файл

    mov qword [sum1], 0     ; обнуляем сумму первой строки
    mov qword [count1], 0   ; обнуляем количество чисел первой строки
    mov qword [sum2], 0     ; обнуляем сумму второй строки
    mov qword [count2], 0   ; обнуляем количество чисел во второй строке

    mov rsi, buffer         ; ставим указатель на начало прочитанного текста
    mov r12, buffer         ; кладем адрес начала буфера в r12
    add r12, [bytes_read]   ; прибавляем размер, получаем адрес конца данных

    xor r8, r8              ; флаг: 0 - читаем 1-ю строку, 1 - читаем 2-ю строку
    xor r13, r13            ; в r13 будем накапливать сумму текущей строки
    xor r14, r14            ; в r14 будем считать количество чисел в строке

parse_element:              ; метка для начала разбора следующего числа
    cmp rsi, r12            ; дошли ли до конца прочитанных данных
    jge show_err            ; если текст оборвался внезапно, это ошибка

    mov al, [rsi]           ; читаем один символ из буфера
    inc rsi                 ; двигаем указатель к следующему символу

    cmp al, ' '             ; проверяем, не пробел ли это
    je parse_element        ; если пробел, просто пропускаем его

    xor r10, r10            ; r10 - флаг знака числа (0 - плюс, 1 - минус)
    cmp al, '-'             ; проверяем, стоит ли знак минус
    jne check_is_digit      ; если минуса нет, проверяем цифру
    mov r10, 1              ; запоминаем, что число отрицательное
    cmp rsi, r12            ; проверяем, есть ли что-то после минуса
    jge show_err            ; если файл кончился сразу после минуса, это ошибка
    mov al, [rsi]           ; берем следующий символ после минуса
    inc rsi                 ; сдвигаем указатель вперед

check_is_digit:             ; проверка, что символ является цифрой
    cmp al, '0'             ; сравниваем с символом '0'
    jl show_err             ; если код меньше нуля, это не цифра (ошибка)
    cmp al, '9'             ; сравниваем с символом '9'
    jg show_err             ; если код больше девятки, это не цифра (ошибка)

    xor rbx, rbx            ; обнуляем регистр rbx для сбора самого числа
accumulate_digit:           ; цикл сбора числа из отдельных цифр
    sub al, '0'             ; превращаем символ цифры в число (от 0 до 9)
    movzx rax, al           ; расширяем один байт цифры до 64 бит
    imul rbx, 10            ; умножаем текущее число на 10 (сдвигаем разряд)
    add rbx, rax            ; прибавляем новую цифру

    cmp rsi, r12            ; проверяем, не дошли ли до конца текста
    jge end_of_buffer       ; если дошли до конца, переходим к сохранению
    mov al, [rsi]           ; берем следующий символ
    inc rsi                 ; сдвигаем указатель вперед
    cmp al, '0'             ; смотрим, цифра ли это (нижняя граница)
    jl check_delimiter      ; если меньше '0', значит число закончилось
    cmp al, '9'             ; смотрим верхнюю границу цифр
    jle accumulate_digit    ; если это цифра от '0' до '9', продолжаем цикл

check_delimiter:            ; проверка разделителей после числа
    cmp al, ' '             ; если после числа идет пробел
    je skip_trailing_spaces ; переходим к пропуску лишних пробелов
    jmp apply_sign          ; иначе сразу идем применять знак к числу

skip_trailing_spaces:       ; цикл пропуска пробелов после числа
    cmp rsi, r12            ; проверяем, не кончился ли текст
    jge end_of_buffer       ; если кончился, идем в конец буфера
    mov al, [rsi]           ; читаем следующий символ
    inc rsi                 ; сдвигаем указатель
    jmp check_delimiter     ; снова проверяем, пробел это или разделитель

end_of_buffer:              ; если файл кончился
    mov al, 10              ; притворяемся, что встретили перенос строки (\n)

apply_sign:                 ; применяем знак к собранному числу
    cmp r10, 1              ; проверяем, был ли флаг минуса
    jne save_element        ; если минуса не было, оставляем как есть
    neg rbx                 ; если был минус, делаем число отрицательным

save_element:               ; сохраняем число в сумму
    add r13, rbx            ; прибавляем число к общей сумме строки
    inc r14                 ; увеличиваем счетчик чисел в строке на 1

    cmp al, ','             ; если разделитель запятая
    je parse_element        ; возвращаемся читать следующее число строки

    cmp al, 13              ; проверяем символ возврата каретки '\r' (для Windows)
    jne test_nl             ; если не '\r', сразу проверяем перенос '\n'
    cmp rsi, r12            ; есть ли символ после '\r'
    jge show_err            ; если файл оборвался на '\r', это ошибка
    mov al, [rsi]           ; читаем следующий символ (ждем '\n')
    inc rsi                 ; сдвигаем указатель

test_nl:                    ; проверка переноса строки
    cmp al, 10              ; проверяем символ новой строки '\n'
    jne show_err            ; если не запятая и не новая строка, формат сломан

    cmp r8, 0               ; смотрим, какую строку мы только что закончили
    jne second_line_finished ; если r8 не 0, значит закончили уже вторую строку

    mov [sum1], r13         ; сохраняем сумму чисел первой строки в память
    mov [count1], r14       ; сохраняем количество чисел первой строки в память
    xor r13, r13            ; сбрасываем сумму в ноль для второй строки
    xor r14, r14            ; сбрасываем количество чисел в ноль для второй строки
    mov r8, 1               ; переключаем флаг на чтение второй строки
    jmp parse_element       ; идем читать числа из второй строки

second_line_finished:       ; обработка завершения второй строки
    mov [sum2], r13         ; сохраняем сумму чисел второй строки в память
    mov [count2], r14       ; сохраняем количество чисел второй строки в память

    mov rax, [count1]       ; берем количество чисел в первой строке
    cmp rax, 0              ; проверяем, были ли вообще числа
    je show_err             ; если чисел 0, файл пустой или испорчен
    cmp rax, [count2]       ; сравниваем количество чисел в строках
    jne show_err            ; если количества не равны, выдаем ошибку

    mov rax, [sum1]         ; кладем сумму первой строки в rax
    sub rax, [sum2]         ; вычитаем сумму второй строки (sum1 - sum2)
    cqo                     ; расширяем rax до пары rdx:rax для деления со знаком
    idiv qword [count1]     ; делим на количество чисел, результат в rax

    mov r15, rax            ; сохраняем итоговый ответ в регистр r15

    mov rbx, [filename]     ; берем адрес строки с именем файла
    xor rdx, rdx            ; обнуляем счетчик длины имени файла
.calc_fn_len:               ; цикл подсчета длины имени файла
    cmp byte [rbx + rdx], 0 ; проверяем, не дошли ли до конца строки (нулевой байт)
    je .do_print_fn         ; если дошли до конца, переходим к выводу
    inc rdx                 ; прибавляем 1 к длине строки
    jmp .calc_fn_len        ; повторяем цикл
.do_print_fn:               ; вывод имени файла
    print rdx, [filename]   ; выводим само имя файла на экран

    print len_colon, colon  ; выводим ": " после имени файла

    mov rax, r15            ; кладем наш ответ обратно в rax для печати
    cmp rax, 0              ; проверяем знак числа
    jge .print_positive     ; если число положительное или 0, сразу печатаем
    push rax                ; сохраняем число в стек перед выводом минуса
    print 1, minus          ; выводим символ минуса '-' на экран
    pop rax                 ; достаем число обратно из стека
    neg rax                 ; делаем число положительным для деления на 10

.print_positive:            ; подготовка к выводу положительного числа
    mov rbx, 10             ; делить будем на 10
    xor rcx, rcx            ; обнуляем счетчик цифр, положенных в стек

.divide_loop:               ; цикл раскладывания числа на отдельные цифры
    xor rdx, rdx            ; обнуляем rdx перед делением
    div rbx                 ; делим rax на 10, остаток (цифра) идет в rdx
    push rdx                ; сохраняем эту цифру в стек
    inc rcx                 ; увеличиваем счетчик сохраненных цифр
    test rax, rax           ; проверяем, осталось ли еще что-то в rax
    jnz .divide_loop        ; если частное не ноль, продолжаем делить

.digit_loop:                ; цикл печати цифр из стека на экран
    pop rax                 ; достаем очередную цифру из стека
    add al, '0'             ; переводим цифру 0..9 в символ '0'..'9'
    mov [digit], al         ; сохраняем символ в переменную digit
    push rcx                ; сохраняем счетчик rcx, так как syscall его меняет
    print 1, digit          ; печатаем один символ цифры на экран
    pop rcx                 ; восстанавливаем счетчик rcx
    dec rcx                 ; уменьшаем количество оставшихся цифр
    jnz .digit_loop         ; если цифры еще остались, повторяем

    print 1, newline        ; выводим перенос строки в самом конце

    mov rax, 60             ; номер команды выхода из программы (sys_exit)
    xor rdi, rdi            ; код возврата 0 (успешно)
    syscall                 ; завершаем программу

show_err:                   ; метка для вывода сообщения об ошибке
    mov rbx, [filename]     ; берем адрес строки с именем файла
    xor rdx, rdx            ; обнуляем счетчик длины имени файла
.err_len_loop:              ; цикл подсчета длины имени файла для ошибки
    cmp byte [rbx + rdx], 0 ; ищем конец строки (нулевой байт)
    je .do_print_err_fn     ; если нашли конец строки, печатаем
    inc rdx                 ; прибавляем 1 к длине
    jmp .err_len_loop       ; продолжаем цикл
.do_print_err_fn:           ; печать имени файла и текста ошибки
    print rdx, [filename]   ; выводим имя файла
    print len_err, msg_err  ; выводим ": файл испорчен\n"

exit_silent:                ; тихий выход без вывода (если не передали аргументы)
    mov rax, 60             ; номер команды выхода (sys_exit)
    xor rdi, rdi            ; код возврата 0
    syscall                 ; выходим из программы